"""Personalization e2e: no-city state, then name/city/teams via the Settings panel. Needs bridge on :8765 with an empty MODI_HOME."""
import asyncio, sys
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome')
        pg = await b.new_page(viewport={'width': 1920, 'height': 1080})
        errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
        await pg.goto('http://127.0.0.1:8765'); await pg.wait_for_timeout(3500)
        print('greet:', await pg.inner_text('#greet'), '| loc:', await pg.inner_text('#loc'))
        print('weather (no city):', await pg.inner_text('#wxcond'), '| tag:', await pg.inner_text('#wxtag'), '| greyed:', await pg.eval_on_selector('#t-weather', 'e=>e.classList.contains("nocity")'))
        print('sports (empty):', (await pg.inner_text('#teamsbody')).replace('\n', ' / '))
        print('globe label:', await pg.inner_text('#globelab'))
        await pg.screenshot(path='/tmp/prof_nocity.png')
        await pg.click('#wxset'); await pg.wait_for_timeout(500)
        await pg.fill('#pf-aname', '<b>x</b>'); await pg.click('#pf-save'); await pg.wait_for_timeout(800)
        print('bad assistant msg:', await pg.inner_text('#pf-msg'), '| title:', await pg.title())
        await pg.fill('#pf-aname', 'Aria'); await pg.fill('#pf-name', 'Sam'); await pg.fill('#pf-city', 'Austin, Texas')
        await pg.click('.chip:text-is("Soccer")'); await pg.click('.chip:text-is("NBA")'); await pg.click('.chip:text-is("F1")')
        await pg.fill('.sportbox:has(.sh:text-is("Soccer")) .srow:has(.lab:text-is("Leagues")) input', 'Serie A'); await pg.keyboard.press('Enter')
        await pg.fill('.sportbox:has(.sh:text-is("Soccer")) .srow:has(.lab:text-is("Teams")) input', 'Chelsea'); await pg.keyboard.press('Enter')
        await pg.fill('.sportbox:has(.sh:text-is("Soccer")) .srow:has(.lab:text-is("Teams")) input', 'Arsenal'); await pg.keyboard.press('Enter')
        await pg.fill('.sportbox:has(.sh:text-is("NBA")) input', 'San Antonio Spurs'); await pg.keyboard.press('Enter')
        await pg.fill('.chips .other', 'Curling'); await pg.keyboard.press('Enter')
        await pg.fill('.sportbox:has(.sh:text-is("Curling")) input', 'Team Example'); await pg.keyboard.press('Enter')
        await pg.screenshot(path='/tmp/prof_editor.png')
        await pg.click('#pf-save'); await pg.wait_for_timeout(4500)
        print('save msg:', await pg.inner_text('#pf-msg'))
        await pg.screenshot(path='/tmp/prof_settings.png')
        await pg.click('#ovx'); await pg.wait_for_timeout(500)
        print('greet:', await pg.inner_text('#greet'), '| loc:', await pg.inner_text('#loc'))
        print('weather:', await pg.inner_text('#wxtitle'), '|', await pg.inner_text('#wxtemp'), await pg.inner_text('#wxcond'), '| tag:', await pg.inner_text('#wxtag'))
        print('tz:', await pg.inner_text('#tz'), '| globe:', (await pg.inner_text('#globelab')), (await pg.inner_text('#globeco')).replace('\n', ' '))
        print('sports:', (await pg.inner_text('#teamsbody')).replace('\n', ' / '))
        await pg.click('[data-ask="0"]'); await pg.wait_for_timeout(2500)
        print('assistant ->', 'title:', await pg.title(), '| hdr:', await pg.eval_on_selector_all('.aname','e=>e.map(x=>x.textContent)'), '| cmd placeholder:', await pg.get_attribute('#cmdin','placeholder'))
        print('ask team caption:', (await pg.inner_text('#caption'))[:120])
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='/tmp/prof_city.png')
        await pg.reload(); await pg.wait_for_timeout(4000)
        print('after reload -> greet:', await pg.inner_text('#greet'), '| weather title:', await pg.inner_text('#wxtitle'))
        # bad city
        await pg.click('.dk[data-m=settings]'); await pg.wait_for_timeout(500)
        print('persisted editor chips:', await pg.eval_on_selector_all('.chip.sel', 'e=>e.map(x=>x.textContent)'), await pg.eval_on_selector_all('.sportbox .tg', 'e=>e.map(x=>x.textContent)'))
        await pg.fill('#pf-city', 'zzzzqqqqxx'); await pg.click('#pf-save'); await pg.wait_for_timeout(2500)
        print('bad city msg:', await pg.inner_text('#pf-msg'))
        print('errors:', errs)
        await b.close()
asyncio.run(main())
